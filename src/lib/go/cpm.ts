export const MIN_LEVEL = 1;
/** Highest level a trainer can reach: 50, plus 1 from a best-buddy boost. */
export const MAX_LEVEL = 51;

export function cpmAt(level: number): number {
  const i = Math.round((level - 1) * 2);
  const v = CPM[i];
  if (v === undefined) throw new RangeError(`No CP multiplier for level ${level}`);
  return v;
}

/** All valid levels from min to max, in half-level steps. */
export function levels(min = MIN_LEVEL, max = MAX_LEVEL): number[] {
  const out: number[] = [];
  for (let l = min; l <= max; l += 0.5) out.push(l);
  return out;
}
